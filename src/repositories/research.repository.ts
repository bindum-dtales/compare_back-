import { supabase } from "../supabase/client.js";
import { dbError } from "../utils/errors.js";
import type { ResearchJobRow } from "../types/research.js";

const TABLE = "research_jobs";

/** Returns null if another active job for the domain won the race (unique violation). */
export async function createJob(job: Pick<ResearchJobRow, "company_name" | "company_domain">): Promise<ResearchJobRow | null> {
  const { data, error } = await supabase.from(TABLE).insert({ ...job, status: "queued", progress: 0 }).select("*").single();
  if (error?.code === "23505") return null;
  if (error) throw dbError(error);
  return data;
}

export async function findJobById(id: string): Promise<ResearchJobRow | null> {
  const { data, error } = await supabase.from(TABLE).select("*").eq("id", id).maybeSingle();
  if (error) throw dbError(error);
  return data;
}

/** The queued or running job for a normalized domain, if any (at most one, by unique index). */
export async function findActiveJobByDomain(domain: string): Promise<ResearchJobRow | null> {
  const { data, error } = await supabase
    .from(TABLE)
    .select("*")
    .eq("company_domain", domain)
    .not("status", "in", "(completed,failed)")
    .maybeSingle();
  if (error) throw dbError(error);
  return data;
}

export async function updateJob(
  id: string,
  patch: Partial<Omit<ResearchJobRow, "id" | "created_at">>,
): Promise<ResearchJobRow> {
  const { data, error } = await supabase.from(TABLE).update(patch).eq("id", id).select("*").single();
  if (error) throw dbError(error);
  return data;
}

/** Oldest queued jobs first. Candidates only: claim each with claimJob before running it. */
export async function listQueuedJobIds(limit: number): Promise<string[]> {
  const { data, error } = await supabase.from(TABLE).select("id").eq("status", "queued").order("created_at").limit(limit);
  if (error) throw dbError(error);
  return data.map((r) => r.id as string);
}

/**
 * Atomically move a job queued → resolving. The `status = 'queued'` filter makes the
 * UPDATE a compare-and-set: of any number of concurrent callers, exactly one gets the row,
 * the rest get null. Only the winner may run the job.
 */
export async function claimJob(id: string): Promise<ResearchJobRow | null> {
  const { data, error } = await supabase
    .from(TABLE)
    .update({ status: "resolving", progress: 10, current_step: "Resolving company", started_at: new Date().toISOString() })
    .eq("id", id)
    .eq("status", "queued")
    .select("*")
    .maybeSingle();
  if (error) throw dbError(error);
  return data;
}

/**
 * Fail jobs that were claimed but haven't finished since `startedBefore` (the worker
 * died mid-job). Without this they'd hold the domain's single active-job slot forever.
 */
export async function failStaleJobs(startedBefore: string, code: string, message: string, exceptIds: string[] = []): Promise<number> {
  let query = supabase
    .from(TABLE)
    .update({ status: "failed", error_code: code, error: message, completed_at: new Date().toISOString() })
    .not("status", "in", "(queued,completed,failed)")
    .lt("started_at", startedBefore);
  // Job ids are uuids (generated by the database), so they are safe inside the filter list.
  if (exceptIds.length) query = query.not("id", "in", `(${exceptIds.join(",")})`);
  const { data, error } = await query.select("id");
  if (error) throw dbError(error);
  return data.length;
}

/** Start and end of every completed job of these companies (the runs that produced their own results). */
export async function listCompletedJobWindows(companyIds: string[]): Promise<Pick<ResearchJobRow, "company_id" | "started_at" | "completed_at">[]> {
  if (!companyIds.length) return [];
  const { data, error } = await supabase.from(TABLE).select("company_id,started_at,completed_at").eq("status", "completed").in("company_id", companyIds);
  if (error) throw dbError(error);
  return data;
}
